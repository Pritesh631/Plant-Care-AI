def _normalise(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower())


_INDEX = {_normalise(k): k for k in _DISEASES}


def split_class_name(class_name: str) -> tuple[str, str]:
    """'Tomato___Late_blight' -> ('Tomato', 'Late blight'). Works for unknown classes too."""
    if "___" in class_name:
        plant, condition = class_name.split("___", 1)
    else:
        plant, condition = class_name, ""
    plant = plant.replace("_", " ").replace(",", "").strip()
    condition = condition.replace("_", " ").strip()
    return plant, condition


def is_healthy_class(class_name: str) -> bool:
    return split_class_name(class_name)[1].lower() == "healthy"


def get_disease_info(class_name: str) -> dict:
    """Return structured info for a model class. Never fabricates unknown entries."""
    key = _INDEX.get(_normalise(class_name))
    plant, condition = split_class_name(class_name)
    if key:
        info = dict(_DISEASES[key])
        info.update(class_name=class_name, info_available=True, verification="ai_generated",
                    sources=[], note=AI_NOTE)
        return info
    if is_healthy_class(class_name):
        return {
            "class_name": class_name, "plant": plant, "disease": "Healthy", "kind": "none",
            "is_healthy": True, "info_available": True, "verification": "ai_generated",
            "sources": [], "note": AI_NOTE,
            "symptoms": ["No obvious disease symptoms detected by the model"],
            "causes": [], "prevention": ["Keep good airflow, balanced nutrition and clean tools",
                                         "Rotate crops where applicable"],
            "treatment": ["No treatment indicated. Continue regular monitoring."],
            "crop_care": ["Water at the base of the plant", "Scout regularly for early symptoms"],
        }
    return {
        "class_name": class_name, "plant": plant, "disease": condition or class_name,
        "kind": "unknown", "is_healthy": False, "info_available": False,
        "verification": "none", "sources": [], "note": "No information stored for this class yet.",
        "symptoms": [], "causes": [], "prevention": [], "treatment": [], "crop_care": [],
    }


def list_known_classes() -> list[str]:
    return list(_DISEASES.keys())
